// Downloads piece sets from lichess-org/lila into public/pieces and generates src/pieces.css
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SETS = ['california', 'staunty', 'maestro', 'cardinal', 'chessnut', 'merida', 'pirouetti', 'kiwen-suwi', 'firi'];
const FILES = ['wK', 'wQ', 'wR', 'wB', 'wN', 'wP', 'bK', 'bQ', 'bR', 'bB', 'bN', 'bP'];
const ROLES = { K: 'king', Q: 'queen', R: 'rook', B: 'bishop', N: 'knight', P: 'pawn' };
const COLORS = { w: 'white', b: 'black' };
const BASE = 'https://raw.githubusercontent.com/lichess-org/lila/master/public/piece';

const LICENSES = `# Piece set licenses

All sets are from lichess-org/lila (public/piece).

- california — Jerry S., CC BY-NC-SA 4.0
- staunty, maestro, cardinal — sadsnake1, CC BY-NC-SA 4.0
- chessnut — Alexis Luengas, Apache 2.0
- merida — Armando Hernandez Marroquin, GPLv2+
- pirouetti — pirouetti, AGPLv3+
- kiwen-suwi — neverRare, CC BY 4.0
- firi — James Faure, CC BY 4.0
`;

const ok = [];
for (const set of SETS) {
  const dir = join(root, 'public', 'pieces', set);
  await mkdir(dir, { recursive: true });
  let good = true;
  for (const f of FILES) {
    try {
      const res = await fetch(`${BASE}/${set}/${f}.svg`);
      const text = await res.text();
      if (!res.ok || !/^\s*(<\?xml|<svg)/.test(text)) throw new Error(`bad content (${res.status})`);
      await writeFile(join(dir, `${f}.svg`), text);
    } catch (e) {
      console.error(`FAIL ${set}/${f}: ${e.message}`);
      good = false;
    }
  }
  if (good) ok.push(set);
}

await writeFile(join(root, 'public', 'pieces', 'LICENSES.md'), LICENSES);

let css = '/* generated by scripts/fetch-pieces.mjs; cburnett (default) comes from chessground */\n';
for (const set of ok)
  for (const f of FILES)
    css += `:root[data-pieces='${set}'] .cg-wrap piece.${COLORS[f[0]]}.${ROLES[f[1]]} { background-image: url('/pieces/${set}/${f}.svg'); }\n`;
await writeFile(join(root, 'src', 'pieces.css'), css);
console.log('ok sets:', ok.join(', '), '| failed:', SETS.filter((s) => !ok.includes(s)).join(', ') || 'none');
